import { chromium } from 'playwright-core';
import { mkdirSync, writeFileSync } from 'node:fs';
const out = 'output/playwright/yanami';
mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
const errors = [];
const checks = [];
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
await context.addInitScript(() => { localStorage.setItem('rag4c.onboarding.v1', '1'); });
const page = await context.newPage();
page.on('pageerror', e => errors.push(e.message));
page.on('response', r => { if (r.url().includes('/themes/yanami/') && !r.ok()) errors.push(`SVG ${r.status()}: ${r.url()}`); });
await page.goto('http://127.0.0.1:1420/query', { waitUntil: 'networkidle' });
await page.getByRole('button', { name: '使用八奈见主题', exact: true }).click();
await page.locator('html[data-theme="anime"]').waitFor();
await page.getByRole('heading', { name: '让每个答案，都能回到它的出处。' }).waitFor();
await page.screenshot({ path: `${out}/query-yanami-desktop.png`, fullPage: true });
checks.push({ theme: await page.locator('html').getAttribute('data-theme'), artwork: await page.locator('.yanami-welcome-art').isVisible() });
await page.reload({ waitUntil: 'networkidle' });
if (await page.locator('html').getAttribute('data-theme') !== 'anime') throw new Error('Theme did not persist');
await page.getByRole('searchbox', { name: '功能搜索', exact: true }).fill('自动化');
await page.getByRole('button', { name: '自动化中心', exact: true }).waitFor();
await page.screenshot({ path: `${out}/navigation-search.png` });
await page.getByRole('button', { name: '清除', exact: true }).click();
for (const [label, theme] of [['暗色','dark'], ['亮色','light']]) {
  await page.getByRole('button', { name: `使用${label}主题`, exact: true }).click();
  if (await page.locator('.yanami-welcome-art').isVisible()) throw new Error('Art leaked into ' + theme);
  await page.screenshot({ path: `${out}/query-${theme}-desktop.png`, fullPage: true });
}
await page.getByRole('button', { name: '使用八奈见主题', exact: true }).click();
await page.getByRole('button', { name: '文档管理', exact: true }).click();
await page.waitForURL('**/documents');
await page.screenshot({ path: `${out}/documents-yanami.png`, fullPage: true });
await page.getByRole('button', { name: '知识问答', exact: true }).click();
await page.getByRole('button', { name: '收起侧栏', exact: true }).click();
await page.getByRole('button', { name: '当前八奈见主题，切换到亮色主题', exact: true }).waitFor();
await page.screenshot({ path: `${out}/query-collapsed.png` });
await page.getByRole('button', { name: '展开侧栏', exact: true }).click();
await page.setViewportSize({ width: 375, height: 812 });
await page.getByRole('button', { name: '打开导航', exact: true }).waitFor();
await page.screenshot({ path: `${out}/query-yanami-mobile.png`, fullPage: true });
checks.push(await page.evaluate(() => ({ viewport: innerWidth, documentWidth: document.documentElement.scrollWidth, bodyWidth: document.body.scrollWidth })));
await page.getByRole('button', { name: '打开导航', exact: true }).click();
await page.getByRole('button', { name: '使用八奈见主题', exact: true }).waitFor();
await page.screenshot({ path: `${out}/navigation-mobile.png`, fullPage: true });
await page.keyboard.press('Escape');
checks.push({ mobileNavigationClosed: await page.getByRole('button', { name: '打开导航', exact: true }).isVisible() });
await page.emulateMedia({ reducedMotion: 'reduce' });
checks.push(await page.locator('.yanami-welcome-art').evaluate(el => ({ animation: getComputedStyle(el).animationDuration, transition: getComputedStyle(el).transitionDuration })));
writeFileSync(`${out}/results.json`, JSON.stringify({ checks, errors }, null, 2));
console.log(JSON.stringify({ checks, errors }, null, 2));
await browser.close();
if (errors.length) process.exitCode = 1;
